// Bakes a 1-degree land/ocean bitmap from the Blue Marble texture into
// src/data/landMask.ts, so the sky view's plan projection can draw a dot-matrix
// Earth without shipping or decoding a 1.4 MB image at runtime.
//
// Run with `npm run land-mask` after changing the texture. The output is
// committed; nothing at build time depends on this script.
//
// Encoding: 360 columns (longitude -180..180) by 180 rows (latitude 90..-90),
// one bit per cell, row-major, most significant bit first, base64.

import sharp from 'sharp';
import { writeFileSync } from 'node:fs';
import { resolve } from 'node:path';

const root = process.cwd();
const COLS = 360;
const ROWS = 180;

// Ocean in this texture is dark blue (deep) to cyan-blue (shelf), so blue
// dominates. Land, including desert and rainforest, has red close to blue or
// above it, and ice caps are bright in every channel.
const isLand = (r, g, b) => r > b * 0.82 || (r > 150 && g > 150 && b > 150);

const { data, info } = await sharp(resolve(root, 'public/textures/earth-blue-marble.jpg'))
  .removeAlpha()
  .raw()
  .toBuffer({ resolveWithObject: true });

const cellW = info.width / COLS;
const cellH = info.height / ROWS;
const bytes = new Uint8Array(Math.ceil((COLS * ROWS) / 8));
let landCells = 0;

for (let row = 0; row < ROWS; row++) {
  for (let col = 0; col < COLS; col++) {
    let land = 0;
    let total = 0;
    // Sample a 4x4 lattice inside the cell rather than every pixel
    for (let sy = 0; sy < 4; sy++) {
      for (let sx = 0; sx < 4; sx++) {
        const x = Math.min(info.width - 1, Math.floor((col + (sx + 0.5) / 4) * cellW));
        const y = Math.min(info.height - 1, Math.floor((row + (sy + 0.5) / 4) * cellH));
        const i = (y * info.width + x) * info.channels;
        if (isLand(data[i], data[i + 1], data[i + 2])) land++;
        total++;
      }
    }
    if (land / total >= 0.5) {
      const bit = row * COLS + col;
      bytes[bit >> 3] |= 0x80 >> (bit & 7);
      landCells++;
    }
  }
}

const source = `// Generated by scripts/gen-land-mask.mjs. Do not edit by hand.
// 1-degree land mask: ${COLS} columns (lon -180..180) x ${ROWS} rows (lat 90..-90),
// one bit per cell, row-major, MSB first, base64.

export const LAND_MASK_COLS = ${COLS};
export const LAND_MASK_ROWS = ${ROWS};
export const LAND_MASK_BASE64 =
  '${Buffer.from(bytes).toString('base64')}';
`;

writeFileSync(resolve(root, 'src/data/landMask.ts'), source);
console.log(`land mask: ${landCells} of ${COLS * ROWS} cells are land (${((100 * landCells) / (COLS * ROWS)).toFixed(1)}%)`);
